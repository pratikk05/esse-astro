#!/usr/bin/env node
/*
  FlowScale generator.

  pnpm flowscale              → regenerate typography.css, spacing.css, flowscale.manifest.json
  pnpm flowscale 40 76        → print the clamp() for a 40px → 76px fluid value
  pnpm flowscale 40 76 768 1440  → same, over a custom viewport range
*/
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { viewport, typography, spacing, spacingMin } from "./flowscale.config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const styles = join(root, "src/styles");

const num = (n, d = 4) => String(Number(n.toFixed(d)));
const rem = (px) => `${num(px / 16)}rem`;

/** clamp(min, intercept + slope·vw, max) — linear between vmin and vmax. */
export function fluid(minPx, maxPx, vmin = viewport.min, vmax = viewport.max) {
  if (minPx === maxPx) return rem(maxPx);
  const slope = (maxPx - minPx) / (vmax - vmin);
  const intercept = minPx - slope * vmin;
  return `clamp(${rem(minPx)}, calc(${rem(intercept)} + ${num(slope * 100)}vw), ${rem(maxPx)})`;
}

// ---- CLI: print a single value ----
const args = process.argv.slice(2).map(Number);
if (args.length >= 2) {
  console.log(fluid(args[0], args[1], args[2] ?? viewport.min, args[3] ?? viewport.max));
  process.exit(0);
}

const header = (what) =>
  `/*\n  GENERATED by tools/flowscale.mjs from tools/flowscale.config.mjs — do not edit by hand.\n  ${what}\n  Fluid range: ${viewport.min}px → ${viewport.max}px viewport. Class numbers = Figma px (16px root).\n*/\n`;

const manifest = { viewport, typography: [], spacing: [], colors: [] };

// ---- Colours: read straight from tokens.css so the style guide can't drift ----
const tokens = readFileSync(join(styles, "tokens.css"), "utf8");
for (const [, name, value, note] of tokens.matchAll(/--color-([\w-]+):\s*([^;]+);(?:[ \t]*\/\*\s*(.*?)\s*\*\/)?/g)) {
  manifest.colors.push({ name, token: `--color-${name}`, value: value.trim(), note: note ?? "" });
}
const tokenMap = (prefix) =>
  Object.fromEntries([...tokens.matchAll(new RegExp(`--${prefix}-([\\w-]+):\\s*([^;]+);`, "g"))].map(([, k, v]) => [k, v.trim()]));
manifest.leading = tokenMap("leading");
manifest.tracking = tokenMap("tracking");
manifest.fonts = tokenMap("font");

// ---- Typography ----
let typo = header("Typography utilities: heading-* (primary), para-* (secondary), text-* (tertiary).");
const safelist = [];
for (const [prefix, group] of Object.entries(typography)) {
  for (const t of group.sizes) {
    const cls = `${prefix}-${t.size}`;
    const value = fluid(t.min, t.size);
    typo += `\n/* ${cls}: ${t.size}px (${rem(t.size)}) · min ${t.min}px · ${t.source} */\n@utility ${cls} {\n`;
    typo += `  font-family: var(${group.family});\n  font-size: ${value};\n`;
    if (t.weight) typo += `  font-weight: ${t.weight};\n`;
    typo += `  line-height: var(--leading-${t.leading});\n  letter-spacing: var(--tracking-${t.tracking});\n}\n`;
    safelist.push(cls);
    manifest.typography.push({ className: cls, family: group.family, size: t.size, rem: rem(t.size), min: t.min, max: t.size, weight: t.weight ?? "inherit", leading: t.leading, tracking: t.tracking, value, source: t.source });
  }
}

// ---- Spacing ----
let space = header("Spacing utilities: spacer-*, gap-figma-*, padding-*, margin-*.");
// Spacing entries are a px number or { px, min } (explicit mobile minimum).
const entry = (v) => (typeof v === "number" ? { px: v, min: spacingMin(v) } : v);
const add = (cls, kind, v, decls) => {
  const { px, min } = entry(v);
  const value = fluid(min, px);
  space += `\n@utility ${cls} {\n${decls(value).map((d) => `  ${d};`).join("\n")}\n}\n`;
  safelist.push(cls);
  manifest.spacing.push({ className: cls, kind, px, rem: rem(px), min, max: px, value });
};

space += "\n/* ---- Vertical spacers ---- */";
for (const v of spacing.spacer) add(`spacer-${entry(v).px}`, "spacer", v, (v) => ["width: 100%", `height: ${v}`, "flex-shrink: 0", "margin: 0"]);

space += "\n/* ---- Gaps (namespaced to avoid Tailwind gap-*) ---- */";
for (const v of spacing.gap) add(`gap-figma-${entry(v).px}`, "gap", v, (v) => [`gap: ${v}`]);

const sides = {
  all: (p) => [p],
  x: (p) => [`${p}-left`, `${p}-right`],
  y: (p) => [`${p}-top`, `${p}-bottom`],
  top: (p) => [`${p}-top`],
  bottom: (p) => [`${p}-bottom`],
  left: (p) => [`${p}-left`],
  right: (p) => [`${p}-right`],
};
for (const prop of ["padding", "margin"]) {
  space += `\n/* ---- ${prop} ---- */`;
  for (const [side, values] of Object.entries(spacing[prop])) {
    for (const v of values) {
      const { px } = entry(v);
      const cls = side === "all" ? `${prop}-${px}` : `${prop}-${side}-${px}`;
      add(cls, side === "all" ? prop : `${prop}-${side}`, v, (val) => sides[side](prop).map((p) => `${p}: ${val}`));
    }
  }
}

// Safelist so every FlowScale class exists for the style guide (it renders class names from data).
const safe = `\n/* Always generate every FlowScale class (style guide renders them from data). */\n@source inline("${safelist.join(" ")}");\n`;

writeFileSync(join(styles, "typography.css"), typo + safe.replace(/@source inline\("[^"]*"\)/, `@source inline("${manifest.typography.map((t) => t.className).join(" ")}")`));
writeFileSync(join(styles, "spacing.css"), space + safe.replace(/@source inline\("[^"]*"\)/, `@source inline("${manifest.spacing.map((t) => t.className).join(" ")}")`));
writeFileSync(join(styles, "flowscale.manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(
  `FlowScale: ${manifest.typography.length} typography + ${manifest.spacing.length} spacing classes, ${manifest.colors.length} colours → src/styles/`,
);
